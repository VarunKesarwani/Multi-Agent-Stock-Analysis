def pipeline(tmp_path):
    p=AnnualReportEmbeddingPipeline(PipelineConfig(failure_log=tmp_path/'failed.jsonl'),qdrant_client=QdrantClient(':memory:'))
    p.embed_texts=lambda texts:[[1.,0.1,0.2] for _ in texts]
    return p


def test_qdrant_resume_and_filter(tmp_path):
    p=pipeline(tmp_path)
    try:
        chunks=[{'document_type':kind,'document_id':kind,'source_file':'same.pdf','chunk_id':0,'text':'Cash flow.'}
                for kind in ['Annual Report','financial_education']]
        assert p.run(chunks).stored==2
        assert p.run(chunks).skipped_existing==2
        hits=p.query('cash',document_type='financial_education').points
        assert len(hits)==1 and hits[0].payload['document_type']=='financial_education'
        assert hits[0].payload['embedding_model']=='nomic-embed-text'
    finally:p.close()


def test_same_dimension_different_model_rejected(tmp_path):
    p=pipeline(tmp_path)
    try:
        p.run([{'text':'cash','chunk_id':0}])
        p.config=replace(p.config,embedding_model='another-model')
        with pytest.raises(ValueError,match='another embedding model'):p.run([{'text':'cash','chunk_id':0}])
    finally:p.close()


def test_legacy_confirmation_and_dimension_guard(tmp_path):
    p=pipeline(tmp_path)
    try:
        p.qdrant.create_collection(p.config.collection_name,vectors_config=models.VectorParams(size=2,distance=models.Distance.COSINE))
        p.qdrant.upsert(p.config.collection_name,[models.PointStruct(id=1,vector=[1.,0.],payload={'text':'legacy'})])
        with pytest.raises(ValueError,match='unlabelled legacy'):p.run([{'text':'new'}])
        p.config=replace(p.config,allow_legacy_embeddings=True)
        with pytest.raises(ValueError,match='expects vectors of size'):p.run([{'text':'new'}])
    finally:p.close()


def test_openai_mapping_and_secret_repr():
    session=Mock()
    session.post.return_value.json.return_value={'data':[{'index':1,'embedding':[2.,1.]},{'index':0,'embedding':[1.,2.]}]}
    cfg=PipelineConfig(embedding_type='openai',embedding_model='text-embedding-3-small',openai_api_key='test-key')
    p=AnnualReportEmbeddingPipeline(cfg,session=session,qdrant_client=QdrantClient(':memory:'))
    try:
        assert p._embed_once(['a','b'])==[[1.,2.],[2.,1.]]
        assert session.post.call_args.kwargs['json']['input']==['a','b']
        assert session.post.call_args.kwargs['headers']['Authorization']=='Bearer test-key'
        assert 'test-key' not in repr(cfg)
    finally:p.close()


def test_full_education_runner_continues_and_resumes(tmp_path,monkeypatch):
    import pymupdf
    from document_ingestion import run_ingestion
    root=tmp_path/'education';root.mkdir()
    (root/'broken.pdf').write_bytes(b'not a PDF')
    with pymupdf.open() as doc:
        doc.new_page().insert_text((72,72),'Operating cash flow is an important financial concept.')
        doc.save(root/'valid.pdf')
    env=tmp_path/'.env';env.write_text(f'EDUCATIONAL_PDF_DIR={root.as_posix()}\n')
    p=pipeline(tmp_path)
    try:
        summary=run_ingestion('education',env,pipeline=p)
        assert summary['documents']==2 and summary['failed_documents']==1
        assert summary['stored']>0
        again=run_ingestion('education',env,pipeline=p)
        assert again['stored']==0 and again['skipped_existing']==summary['stored']
    finally:p.close()


