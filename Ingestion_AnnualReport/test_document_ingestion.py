def test_education_metadata_and_ids(tmp_path,monkeypatch):
    import pymupdf4llm
    cfg=PipelineConfig(max_chunk_chars=120,chunk_overlap_chars=20)
    root=tmp_path/'education';root.mkdir();pdf=root/'lesson.pdf';pdf.write_bytes(b'fixture')
    pdf.with_suffix('.metadata.json').write_text(json.dumps({'source':'Zerodha Varsity','topic':'cash_flow'}))
    monkeypatch.setattr(pymupdf4llm,'to_markdown',lambda *a,**k:[
        {'metadata':{'page_number':1},'text':'# Cash flow\n'+'cash flow example '*50},
        {'metadata':{'page_number':2},'text':'## Ratios\nProfit is not cash.'}])
    chunks=education_chunks(pdf,root,settings(tmp_path),cfg)
    assert {c['page_number'] for c in chunks}=={1,2}
    assert all(c['document_type']=='financial_education' and c['topic']=='cash_flow' for c in chunks)
    assert all('symbol' not in c and 'year' not in c and len(c['text'])<=120 for c in chunks)
    assert prepare_chunks(chunks,120,20)==prepare_chunks(chunks,120,20)
    other=root/'other';other.mkdir();other_pdf=other/'lesson.pdf';other_pdf.write_bytes(pdf.read_bytes())
    assert education_chunks(other_pdf,root,settings(tmp_path),cfg)[0]['document_id']!=chunks[0]['document_id']


