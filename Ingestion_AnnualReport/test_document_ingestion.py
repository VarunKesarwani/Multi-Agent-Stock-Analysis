def test_env_paths_and_precedence(tmp_path,monkeypatch):
    env=tmp_path/'.env'
    env.write_text('EDUCATIONAL_PDF_DIR=lessons\nCHUNK_SIZE_CHARS=700\nCHUNK_OVERLAP_CHARS=70\n')
    monkeypatch.setenv('CHUNK_SIZE_CHARS','900')
    monkeypatch.chdir(tmp_path.parent)
    assert DocumentSettings.from_env(env).educational_pdf_dir==tmp_path/'lessons'
    assert PipelineConfig.from_env(env).max_chunk_chars==900
    monkeypatch.setenv('CHUNK_OVERLAP_CHARS','900')
    with pytest.raises(ValueError):PipelineConfig.from_env(env)


